import re

print("=" * 45)
print("             RESUME PARSER")
print("=" * 45)

resume_text = input("\nPaste the resume text here:\n\n")

# Extract email address
email_match = re.search(
    r'[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}',
    resume_text
)
email = email_match.group() if email_match else "Not found"

# Extract phone number
phone_match = re.search(
    r'(?:\+?\d{1,3}[-.\s]?)?\d{10}',
    resume_text
)
phone = phone_match.group() if phone_match else "Not found"

# Extract candidate name using the first non-empty line
lines = [line.strip() for line in resume_text.splitlines() if line.strip()]
name = lines[0] if lines else "Not found"

# Predefined skills list
skills_list = [
    "Python", "Java", "C", "C++", "HTML",
    "CSS", "JavaScript", "SQL", "Machine Learning",
    "Artificial Intelligence", "Data Analysis",
    "Excel", "Communication", "Flask"
]

# Identify skills in resume text
found_skills = []

for skill in skills_list:
    pattern = r'\b' + re.escape(skill) + r'\b'
    if re.search(pattern, resume_text, re.IGNORECASE):
        found_skills.append(skill)

# Display extracted information
print("\n" + "=" * 45)
print("          EXTRACTED RESUME DETAILS")
print("=" * 45)

print("\nCandidate Name :", name)
print("Email Address  :", email)
print("Phone Number   :", phone)

print("\nSkills Identified:")
if found_skills:
    for skill in found_skills:
        print("-", skill)
else:
    print("No predefined skills found.")

print("\n" + "=" * 45)
print("       RESUME PARSING COMPLETED")
print("=" * 45)