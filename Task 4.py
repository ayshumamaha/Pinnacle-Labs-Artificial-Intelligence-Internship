import difflib
import re

print("=" * 45)
print("             AUTOCORRECT TOOL")
print("=" * 45)

# Predefined vocabulary
dictionary = [
    "hello", "world", "python", "programming",
    "computer", "science", "artificial", "intelligence",
    "machine", "learning", "student", "teacher",
    "education", "technology", "development",
    "application", "project", "software", "language",
    "beautiful", "welcome", "friend", "school",
    "college", "information", "communication",
    "keyboard", "internet", "database", "analysis",
    "knowledge", "excellent", "important", "example",
    "function", "variable", "algorithm", "system"
]

text = input("\nEnter a sentence: ")

# Split sentence into words
words = re.findall(r"[A-Za-z']+", text)

corrected_words = []
corrections = []

for word in words:
    lower_word = word.lower()

    if lower_word in dictionary:
        corrected_words.append(word)
    else:
        suggestions = difflib.get_close_matches(
            lower_word,
            dictionary,
            n=1,
            cutoff=0.65
        )

        if suggestions:
            suggestion = suggestions[0]

            # Preserve initial capitalization
            if word[0].isupper():
                suggestion = suggestion.capitalize()

            corrected_words.append(suggestion)
            corrections.append((word, suggestion))
        else:
            corrected_words.append(word)

# Display results
corrected_text = " ".join(corrected_words)

print("\n" + "=" * 45)
print("             CORRECTION RESULT")
print("=" * 45)

print("\nOriginal Text:")
print(text)

print("\nCorrected / Suggested Text:")
print(corrected_text)

print("\nSpelling Suggestions:")

if corrections:
    for original, suggestion in corrections:
        print(f"{original}  ->  {suggestion}")
else:
    print("No spelling suggestions found.")

print("\n" + "=" * 45)
print("       AUTOCORRECT COMPLETED")
print("=" * 45)