import re

print("=" * 50)
print("             TEACHABLE MACHINE")
print("=" * 50)

# Create categories and provide training examples
categories = {}

number_of_categories = int(input("\nHow many categories do you want to create? "))

for i in range(number_of_categories):
    category_name = input(f"\nEnter name for category {i + 1}: ").strip()

    examples = input(
        f"Enter example sentences for {category_name}, separated by | :\n"
    )

    categories[category_name] = [
        example.strip().lower()
        for example in examples.split("|")
        if example.strip()
    ]

# Function to convert text into words
def get_words(text):
    return set(re.findall(r'\b[a-zA-Z]+\b', text.lower()))

# Classify new text based on similarity with examples
def classify_text(new_text):
    new_words = get_words(new_text)

    if not new_words:
        return "No category could be identified."

    scores = {}

    for category, examples in categories.items():
        best_score = 0

        for example in examples:
            example_words = get_words(example)

            if not example_words:
                continue

            common_words = new_words.intersection(example_words)
            union_words = new_words.union(example_words)

            similarity = len(common_words) / len(union_words)

            if similarity > best_score:
                best_score = similarity

        scores[category] = best_score

    if not scores or max(scores.values()) == 0:
        return "No matching category found."

    predicted_category = max(scores, key=scores.get)
    return predicted_category

# Accept a new input
print("\n" + "=" * 50)
print("             TRAINING COMPLETED")
print("=" * 50)

new_text = input("\nEnter a new sentence to classify: ")

prediction = classify_text(new_text)

print("\n" + "=" * 50)
print("             PREDICTION RESULT")
print("=" * 50)

print("Input Text:", new_text)
print("Predicted Category:", prediction)

print("\n" + "=" * 50)