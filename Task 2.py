import requests

print("=" * 45)
print("             TRANSLATOR APP")
print("=" * 45)

print("\nLanguage Codes:")
print("English: en | Tamil: ta | Hindi: hi")
print("French: fr | Spanish: es | German: de")
print("Japanese: ja | Telugu: te | Malayalam: ml")

text = input("\nEnter the text to translate: ").strip()
source = input("Enter source language code: ").strip().lower()
target = input("Enter target language code: ").strip().lower()

if not text:
    print("\nPlease enter some text.")

elif source == target:
    print("\nBoth languages are the same.")
    print("Translation:", text)

else:
    try:
        url = "https://api.mymemory.translated.net/get"

        params = {
            "q": text,
            "langpair": source + "|" + target
        }

        response = requests.get(url, params=params, timeout=20)

        response.raise_for_status()

        data = response.json()

        if data.get("responseStatus") == 200:
            translated_text = data["responseData"]["translatedText"]

            print("\n" + "=" * 45)
            print("          TRANSLATION RESULT")
            print("=" * 45)

            print("\nOriginal Text:", text)
            print("Translated Text:", translated_text)

            print("\nTranslation completed successfully!")

        else:
            print("\nTranslation service returned an error.")
            print("Details:", data.get("responseDetails"))

    except requests.exceptions.Timeout:
        print("\nRequest timed out. Please try again.")

    except requests.exceptions.RequestException as error:
        print("\nNetwork error:", error)

    except Exception as error:
        print("\nTranslation failed:", error)

print("\n" + "=" * 45)